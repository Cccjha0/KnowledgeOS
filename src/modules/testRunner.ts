function object(value: JsonValue | undefined, code: string): JsonObject {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new PkbError(code, "Expected an object.");
  return value;
}

function requiredString(value: JsonValue | undefined, label: string): string {
  if (typeof value !== "string" || !value.trim()) throw new PkbError("MODULE_TEST_FIXTURE_INVALID", `${label} is required.`);
  return value;
}

function lookup(data: JsonObject, dotted: string): JsonValue | undefined {
  let current: JsonValue | undefined = data;
  for (const part of dotted.split(".")) {
    if (Array.isArray(current)) {
      const index = Number(part);
      if (!Number.isInteger(index) || index < 0) return undefined;
      current = current[index];
      continue;
    }
    if (!current || typeof current !== "object") return undefined;
    current = (current as JsonObject)[part];
  }
  return current;
}

function fixtureFields(manifest: JsonObject, fixture: JsonObject): JsonObject {
  const form = object(manifest.instance_form, "MODULE_TEST_MANIFEST_INVALID");
  const fields = Array.isArray(form.fields) ? form.fields : [];
  const output: JsonObject = {};
  for (const raw of fields) {
    const field = object(raw as JsonValue, "MODULE_TEST_MANIFEST_INVALID");
    const key = requiredString(field.key, "instance_form.fields[].key");
    const value = lookup(fixture, key);
    if (value !== undefined) output[key] = value;
  }
  return output;
}

function check(category: ModuleTestCheck["category"], status: ModuleTestCheck["status"], message: string, details?: JsonObject): ModuleTestCheck {
  return { category, status, message, details: details ?? null };
}

async function contentHash(root: string): Promise<string> {
  const digest = createHash("sha256");
  for (const file of (await listFilesRecursive(root)).sort()) {
    const relative = path.relative(root, file).replaceAll(path.sep, "/");
    // Test reports are generated by this runner.  Including a previous report
    // would make the module checksum depend on the last test invocation.
    if (relative === "module-test-report.json" || relative === "validation-report.json") continue;
    digest.update(relative);
    digest.update(await fs.readFile(file));
  }
  return `sha256:${digest.digest("hex")}`;
}

function gitCommit(engineRoot: string): string | null {
  try { return execFileSync("git", ["-C", engineRoot, "rev-parse", "HEAD"], { encoding: "utf8", windowsHide: true }).trim() || null; }
  catch { return null; }
}

function pythonVersion(): string | null {
  const result = spawnSync("python", ["--version"], { encoding: "utf8", windowsHide: true });
  return result.status === 0 ? (result.stdout || result.stderr).trim() || null : null;
}

function nestedValue(data: JsonObject, dotted: string): JsonValue | undefined { return lookup(data, dotted); }

function valuesEqual(left: JsonValue | undefined, right: JsonValue | undefined): boolean { return JSON.stringify(left) === JSON.stringify(right); }

function promptInvariantResult(output: JsonObject, fixture: JsonObject): { ok: boolean; errors: string[] } {
  const errors: string[] = [];
  const expectedFacts = Array.isArray(fixture.expected_facts) ? fixture.expected_facts : [];
  for (const raw of expectedFacts) {
    const fact = object(raw as JsonValue, "MODULE_TEST_PROMPT_FIXTURE_INVALID");
    const field = requiredString(fact.path, "prompt expected_facts[].path");
    if (!valuesEqual(nestedValue(output, field), fact.value)) errors.push(`fact ${field} was not preserved`);
  }
  const uncertainPaths = Array.isArray(fixture.uncertain_paths) ? fixture.uncertain_paths : [];
  for (const raw of uncertainPaths) {
    if (typeof raw !== "string") continue;
    const value = nestedValue(output, raw);
    if (!(value === null || value === undefined || value === "unknown" || (Array.isArray(value) && value.length === 0))) errors.push(`uncertain field ${raw} was made definite`);
  }
  const rendered = JSON.stringify(output);
  for (const raw of Array.isArray(fixture.forbidden_values) ? fixture.forbidden_values : []) {
    if (typeof raw === "string" && rendered.includes(raw)) errors.push(`forbidden value ${raw} was invented`);
  }
  return { ok: errors.length === 0, errors };
}

